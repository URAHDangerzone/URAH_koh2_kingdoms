        public static string Get(string key)
        {
            string lang = Defs.Language ?? "en";
            if (lang.StartsWith("de") && De.TryGetValue(key, out string de))
            {
                return de;
            }
            return En.TryGetValue(key, out string en) ? en : key;
        }
